"""Harvest materials (docs/design/entity-ai-overhaul/README.md section 7): four items, their icons, names and
descriptions, and the recipes that use them. Run on its own: python tools/gen_materials.py

- backrooms:mothquill   a Deathmoth larval quill; coats a spear or arrows with venom (src/Entities/Venom.cs)
- backrooms:spidersilk  a Giant Spider's silk; 2 make a flax twine
- backrooms:clumpsinew  a Clump's dried sinew; stands in for twine in bows and slings, 4 make a rope
- backrooms:mothjelly   Level 5 hive jelly; set down, it draws male Deathmoths and Death Rats for a minute
"""
from PIL import ImageDraw

import gen_loop as L
from gen_textures import save, sprite


def px(img, x, y, c):
    if 0 <= x < img.width and 0 <= y < img.height:
        img.putpixel((x, y), c)


def mothquill():
    img = sprite()
    d = ImageDraw.Draw(img)
    pale, hi, lo = (232, 224, 200, 255), (250, 246, 232, 255), (170, 160, 134, 255)
    dark = (44, 36, 40, 255)
    # a hollow quill lying on the diagonal, the open end up and left, the dark tip down and right
    d.line([(6, 24), (24, 6)], fill=lo, width=5)
    d.line([(6, 23), (23, 6)], fill=pale, width=3)
    d.line([(7, 22), (22, 7)], fill=hi)
    d.ellipse([4, 4, 9, 9], fill=lo)          # the hollow, open end
    d.ellipse([5, 5, 8, 8], fill=(70, 62, 58, 255))
    d.line([(22, 8), (27, 3)], fill=dark, width=3)  # the dark tip
    d.point((28, 2), fill=dark)
    for t in range(4):                         # a few barbs along the shaft
        px(img, 12 + t * 3, 23 - t * 3, lo)
    save(img, "item/mothquill.png")


def spidersilk():
    img = sprite()
    d = ImageDraw.Draw(img)
    a, b, c = (214, 216, 218, 255), (172, 176, 182, 255), (240, 242, 244, 255)
    # a skein: several loops of fine silk wound round, tied at the middle
    for i, (x0, y0, x1, y1) in enumerate([(5, 9, 27, 24), (6, 7, 26, 26), (8, 6, 24, 27), (4, 12, 28, 21), (7, 8, 25, 25)]):
        d.ellipse([x0, y0, x1, y1], outline=(a, b, c, a, b)[i])
    d.rectangle([14, 13, 17, 19], fill=(110, 100, 84, 255))   # the tie
    d.line([(14, 15), (17, 15)], fill=(150, 138, 116, 255))
    d.line([(16, 19), (18, 27)], fill=b)                       # a loose end
    save(img, "item/spidersilk.png")


def clumpsinew():
    img = sprite()
    d = ImageDraw.Draw(img)
    base, hi, lo = (206, 186, 160, 255), (232, 214, 188, 255), (140, 116, 96, 255)
    pink = (196, 150, 140, 255)
    # a coil of dried sinew: concentric loops, flattened, with a tail
    for k, r in enumerate((11, 8, 5)):
        d.ellipse([16 - r, 17 - int(r * 0.7), 16 + r, 17 + int(r * 0.7)], outline=(lo, base, hi)[k], width=2)
    d.ellipse([13, 15, 19, 19], fill=pink)
    d.line([(24, 20), (28, 26), (30, 28)], fill=base, width=2)
    d.point((29, 27), fill=lo)
    save(img, "item/clumpsinew.png")


def mothjelly():
    img = sprite()
    d = ImageDraw.Draw(img)
    amber, hi, lo, deep = (222, 150, 40, 255), (250, 205, 100, 255), (150, 80, 20, 255), (184, 108, 28, 255)
    d.ellipse([6, 11, 26, 27], fill=lo)
    d.ellipse([7, 10, 25, 25], fill=amber)
    d.ellipse([10, 16, 24, 25], fill=deep)
    d.ellipse([10, 12, 15, 16], fill=hi)           # the wet shine
    d.point((16, 12), fill=hi)
    d.ellipse([21, 8, 24, 11], fill=amber)          # a drip curled up the side
    save(img, "item/mothjelly.png")


def items():
    mothquill()
    spidersilk()
    clumpsinew()
    mothjelly()
    for code, cls, stack in (("mothquill", None, 32), ("spidersilk", None, 32), ("clumpsinew", None, 32),
                             ("mothjelly", "BackroomsMothJelly", 8)):
        L.write_json(L.item(code, "item/" + code, cls=cls, extra={"maxstacksize": stack}, ground={"layout": "Quadrants"}),
                     "itemtypes", code + ".json", comment="Generated by tools/gen_materials.py. See docs/design/entity-ai-overhaul/README.md section 7.")
    L.LANG.update({
        "item-mothquill": "Deathmoth Quill",
        "itemdesc-mothquill": "A hollow quill, a hand's length, pale with a dark tip, shed by a larva. Combine it with a spear in the crafting grid to coat the spear in venom (three hits), or with eight arrows to coat them (one hit each).",
        "item-spidersilk": "Spider Silk",
        "itemdesc-spidersilk": "A skein of grey-white silk, strong and very fine. Two make a flax twine in the crafting grid.",
        "item-clumpsinew": "Clump Sinew",
        "itemdesc-clumpsinew": "A coil of dried pale sinew. It does for string: bows and slings can be made with it in place of twine or rope, and four make a rope.",
        "item-mothjelly": "Moth Jelly",
        "itemdesc-mothjelly": "A lump of amber jelly from a Deathmoth hive. Right-click to set it down: for a minute it draws every male Deathmoth and Death Rat within twenty-four blocks to it.",
        "venom-name": "{0} (envenomed, {1})",
        "venom-name-arrow": "{0} (envenomed)",
        "venom-info": "The next {0} hits poison what they wound: 1 damage every 2 seconds for 6 seconds.",
        "venom-info-arrow": "Poisons what it wounds: 1 damage every 2 seconds for 6 seconds.",
    })


def recipes():
    quill = {"type": "item", "code": "backrooms:mothquill"}
    # Venom coating. The result keeps the spear's own attributes (its wear included) and adds the venom
    L.write_recipe({
        "ingredientPattern": "SQ",
        "ingredients": {"S": {"type": "item", "code": "game:spear-*", "name": "spear"}, "Q": quill},
        "width": 2, "height": 1, "shapeless": True,
        "copyAttributesFrom": "S",
        "name": "envenomed spear",
        "output": {"type": "item", "code": "game:spear-{spear}", "attributes": {"backrooms:venom": 3}},
    }, "venom-spear")
    L.write_recipe({
        "ingredientPattern": "AQ",
        "ingredients": {"A": {"type": "item", "code": "game:arrow-*", "name": "arrow", "quantity": 8}, "Q": quill},
        "width": 2, "height": 1, "shapeless": True,
        "name": "envenomed arrows",
        "output": {"type": "item", "code": "game:arrow-{arrow}", "quantity": 8, "attributes": {"backrooms:venom": 1}},
    }, "venom-arrows")
    # Silk to twine
    L.write_recipe({
        "ingredientPattern": "SS",
        "ingredients": {"S": {"type": "item", "code": "backrooms:spidersilk"}},
        "width": 2, "height": 1, "shapeless": True,
        "output": {"type": "item", "code": "game:flaxtwine"},
    }, "silk-twine")
    # Sinew: rope, and the bows and slings with sinew in place of twine and rope
    sinew = {"type": "item", "code": "backrooms:clumpsinew"}
    L.write_recipe({
        "ingredientPattern": "SS,SS",
        "ingredients": {"S": sinew},
        "width": 2, "height": 2, "shapeless": True,
        "output": {"type": "item", "code": "game:rope"},
    }, "sinew-rope")
    L.write_recipe({
        "ingredientPattern": "_ST,S_T,_ST",
        "ingredients": {"S": {"type": "item", "code": "game:stick"}, "T": sinew},
        "width": 3, "height": 3,
        "name": "simple bow (sinew)",
        "output": {"type": "item", "code": "game:bow-simple"},
    }, "sinew-bow")
    L.write_recipe({
        "ingredientPattern": "_FT,BLT,_FT",
        "ingredients": {"B": {"type": "item", "code": "game:bowstave-long-dry"}, "T": sinew,
                        "L": {"type": "item", "code": "game:leather-normal-plain"}, "F": {"type": "item", "code": "game:{coating}"}},
        "allowedVariants": {"coating": ["fat-rendered", "resin", "beeswax"]},
        "width": 3, "height": 3,
        "name": "long bow (sinew)",
        "output": {"type": "item", "code": "game:bow-long"},
    }, "sinew-longbow")
    for n, leather in enumerate((
            {"type": "item", "code": "game:leather-normal-plain"},
            {"type": "item", "code": "game:hide-pelt-*", "tags": {"anyOf": ["size-small", "size-medium"]}}), 1):
        L.write_recipe({
            "ingredientPattern": "T,L",
            "ingredients": {"T": sinew, "L": leather},
            "requiresTrait": "improviser",
            "width": 1, "height": 2,
            "name": "sling (sinew)",
            "output": {"type": "item", "code": "game:sling"},
        }, f"sinew-sling-{n}")


def main():
    L.LANG.clear()
    items()
    recipes()
    L.merge_lang()
    print(f"gen_materials: {len(L.LANG)} names")


if __name__ == "__main__":
    main()
