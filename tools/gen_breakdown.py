def carpet_worn_texture():
    """The worn armour's skin: vanilla's leather set recoloured to Level 0's carpet, quilted (reads the game's own texture)."""
    src = os.path.join(VANILLA, "assets", "survival", "textures", "entity", "humanoid", "serapharmor", "sewn", "leather.png")
    img = Image.open(src).convert("RGBA")
    px = img.load()
    lo, hi = (74, 64, 44), (196, 176, 130)
    for y in range(img.height):
        for x in range(img.width):
            r, g, b, a = px[x, y]
            if not a:
                continue
            lum = (0.299 * r + 0.587 * g + 0.114 * b) / 255
            lum = max(0.0, min(1.0, (lum - 0.12) / 0.55))
            col = [lo[i] + (hi[i] - lo[i]) * lum for i in range(3)]
            # Quilting: a diamond of stitched seams across the panels, a button at each crossing
            if (x + y) % 6 == 0 or (x - y) % 6 == 0:
                col = [c * 0.8 for c in col]
            if (x + y) % 6 == 0 and (x - y) % 6 == 0:
                col = [min(255, c * 1.25) for c in col]
            px[x, y] = (int(col[0]), int(col[1]), int(col[2]), a)
    path = os.path.join(ASSETS, "textures", "entity", "humanoid", "serapharmor", "carpet.png")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    img.save(path)


