def pleather_worn_texture():
    """The worn armour's skin: vanilla's leather set recoloured to black vinyl (reads the game's own texture)."""
    src = os.path.join(VANILLA, "assets", "survival", "textures", "entity", "humanoid", "serapharmor", "sewn", "leather.png")
    img = Image.open(src).convert("RGBA")
    px = img.load()
    for y in range(img.height):
        for x in range(img.width):
            r, g, b, a = px[x, y]
            if not a:
                continue
            lum = (0.299 * r + 0.587 * g + 0.114 * b) / 255
            v = 14 + 70 * lum
            px[x, y] = (int(v), int(v), int(v * 1.1 + 2), a)
    path = os.path.join(ASSETS, "textures", "entity", "humanoid", "serapharmor", "pleather.png")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    img.save(path)


