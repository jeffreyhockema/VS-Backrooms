"""Assets for breaking the building down (src/Salvage/Breakdown.cs). Run on its own: python tools/gen_breakdown.py

The structure of the Backrooms breaks like anything in Vintage Story, but breaks down: concrete, brick and tile into
rubble, drywall into dust and the odd stud, timber into splinters. Rubble is the one thing the walls give in plenty,
and it is only good for building rough: four lumps stacked dry make a block of rubble masonry, to wall in a home with.

- The rubble item and the rubble masonry block (textures, types, the recipe).
- The words: their names, and the block info shown on a block that will not break.
"""
import json
import os
import random

from PIL import Image, ImageDraw

from detail_kit import ground_storable
from gen_textures import hexrgb, noise_fill, save, shade, sprite, S

ROOT = os.path.join(os.path.dirname(__file__), "..")
ASSETS = os.path.join(ROOT, "assets", "backrooms")
NL = "\n"

LANG = {}


def write_json(data, *rel, comment=None):
    path = os.path.join(ASSETS, *rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    text = json.dumps(data, indent="\t", ensure_ascii=False) + NL
    if comment:
        text = "// " + comment + NL + text
    with open(path, "w", encoding="utf-8", newline=NL) as f:
        f.write(text)


# ======================= Rubble =======================

GREYS = [0x8A8A86, 0x7C7C78, 0x96948E, 0x6E6E6A, 0xA09C92]


def rubble_sprite():
    """A few broken lumps of concrete, one with a stub of plaster still on it."""
    img = sprite()
    d = ImageDraw.Draw(img)
    rng = random.Random(9301)
    lumps = [(4, 14, 15, 26), (13, 8, 25, 20), (16, 19, 28, 28), (7, 5, 14, 13)]
    for i, (x0, y0, x1, y1) in enumerate(lumps):
        c = hexrgb(GREYS[i % len(GREYS)]) + (255,)
        pts = [(x0 + rng.randint(0, 2), y0), (x1, y0 + rng.randint(0, 3)), (x1 - rng.randint(0, 2), y1),
               (x0, y1 - rng.randint(0, 3))]
        d.polygon(pts, fill=c, outline=shade(c, 0.6))
        for _ in range(6):  # aggregate
            x, y = rng.randint(x0 + 1, x1 - 1), rng.randint(y0 + 1, y1 - 1)
            img.putpixel((x, y), shade(c, 0.75))
        d.line([pts[0], pts[1]], fill=shade(c, 1.2))  # the lit edge
    d.rectangle([14, 8, 19, 10], fill=(214, 206, 180, 255))  # plaster skin on the top lump
    save(img, "item/salvage/rubble.png")


def masonry_texture(seed, name):
    """Lumps of rubble stacked dry, grey concrete with here a bit of brick, here a bit of tile, dark gaps between."""
    img = noise_fill(hexrgb(0x3A3936), 6, seed)
    d = ImageDraw.Draw(img)
    rng = random.Random(seed + 1)
    y = 0
    while y < S:
        h = rng.randint(5, 8)
        x = -rng.randint(0, 6)
        while x < S:
            w = rng.randint(6, 11)
            pick = rng.random()
            base = hexrgb(0x9A6450) if pick < 0.12 else hexrgb(0xC9C2B0) if pick < 0.2 else hexrgb(rng.choice(GREYS))
            c = base + (255,)
            d.rectangle([x + 1, y + 1, x + w - 1, y + h - 1], fill=c)
            for _ in range(w * h // 6):
                px, py = rng.randint(x + 1, x + w - 1), rng.randint(y + 1, y + h - 1)
                if 0 <= px < S and 0 <= py < S:
                    img.putpixel((px, py), shade(c, rng.uniform(0.8, 1.1)))
            d.line([x + 1, y + 1, x + w - 1, y + 1], fill=shade(c, 1.15))  # top edges catch the light
            d.line([x + 1, y + h - 1, x + w - 1, y + h - 1], fill=shade(c, 0.7))
            x += w
        y += h
    save(img, f"block/{name}.png")


def rubble_item():
    write_json(ground_storable({
        "code": "rubble",
        "maxstacksize": 64,
        "texture": {"base": "item/salvage/rubble"},
        "creativeinventory": {"general": ["*"], "items": ["*"]},
        "materialDensity": 2200,
        "guiTransform": {"rotation": {"x": 0, "y": 0, "z": 0}, "origin": {"x": 0.5, "y": 0.5, "z": 0.5}, "scale": 1},
        "tpHandTransform": {"translation": {"x": -0.75, "y": -0.4, "z": -0.55}, "rotation": {"x": 0, "y": -45, "z": -10}, "scale": 0.6},
        "groundTransform": {"rotation": {"x": 90, "y": 0, "z": 0}, "origin": {"x": 0.5, "y": 0, "z": 0.5}, "scale": 2},
    }, "Messy12"), "itemtypes", "salvage", "rubble.json",
        comment="Generated by tools/gen_breakdown.py. Broken concrete, brick and plaster: what a wall comes down to.")
    LANG["item-rubble"] = "Rubble"
    LANG["itemdesc-rubble"] = ("Lumps of broken concrete, brick and plaster: what a wall comes down to. "
                               "Four, stacked dry, make a block of rubble masonry.")


def rubble_block():
    masonry_texture(9310, "rubblemasonry1")
    masonry_texture(9320, "rubblemasonry2")
    write_json({
        "code": "rubblemasonry",
        "creativeinventory": {"general": ["*"], "construction": ["*"]},
        "blockmaterial": "Stone",
        "drawtype": "cube",
        "textures": {"all": {"base": "block/rubblemasonry1", "alternates": [
            {"base": "block/rubblemasonry1"}, {"base": "block/rubblemasonry2"}]}},
        "resistance": 4,
        "lightAbsorption": 99,
        "randomizeAxes": "xyz",  # (graphics pass D4) a wall's column picks its versions by height too
        "sounds": {"walk": "game:walk/stone", "place": "game:block/loosestone",
                   "break": "game:block/rock-break-pickaxe", "hit": "game:block/rock-hit-pickaxe"},
    }, "blocktypes", "rubblemasonry.json",
        comment="Generated by tools/gen_breakdown.py. Rubble stacked dry into a rough block: walls for a home, made of the walls that were in the way.")
    write_json({
        "ingredientPattern": "RR,RR",
        "ingredients": {"R": {"type": "item", "code": "rubble"}},
        "width": 2,
        "height": 2,
        "output": {"type": "block", "code": "rubblemasonry", "quantity": 1},
    }, "recipes", "grid", "rubblemasonry.json")
    LANG["block-rubblemasonry"] = "Rubble Masonry"
    LANG["blockdesc-rubblemasonry"] = "Broken concrete stacked dry into a rough block. Ugly, solid, and yours."


def words():
    LANG["blockinfo-unbreakable"] = "Part of what holds the Backrooms together: nothing you carry will break it."


def merge_lang():
    """Adds the names to lang/en.json without disturbing its layout: existing keys updated in place, new ones appended."""
    import re
    tab = "\t"
    path = os.path.join(ASSETS, "lang", "en.json")
    with open(path, encoding="utf-8") as f:
        text = f.read()
    new_lines = []
    for key, value in LANG.items():
        line = tab + json.dumps(key) + ": " + json.dumps(value, ensure_ascii=False)
        pattern = re.compile("^" + tab + re.escape(json.dumps(key)) + ":.*?(,?)$", re.M)
        if pattern.search(text):
            text = pattern.sub(lambda m: line + m.group(1), text, count=1)
        else:
            new_lines.append(line)
    if new_lines:
        body = text.rstrip().rpartition("}")[0].rstrip()
        if not body.endswith(",") and not body.endswith("{"):
            body += ","
        text = body + NL + NL + ("," + NL).join(new_lines) + NL + "}" + NL
    with open(path, "w", encoding="utf-8", newline=NL) as f:
        f.write(text)
    json.loads(text)


def main():
    rubble_sprite()
    rubble_item()
    rubble_block()
    words()
    merge_lang()
    print(f"gen_breakdown: {len(LANG)} names")


if __name__ == "__main__":
    main()
