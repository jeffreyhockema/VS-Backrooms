def heather(ctx, base, amount=0.10, chance=0.22):
    """Heathered knit: flecks of lighter and darker yarn."""
    for yy in range(ctx.h):
        for xx in range(ctx.w):
            r = ctx.rng.random()
            if r < chance / 2:
                scale_px(ctx, xx, yy, 1 + amount)
            elif r < chance:
                scale_px(ctx, xx, yy, 1 - amount)


def rib(ctx, y0, y1, k=0.82):
    """Ribbing (a cuff, a waistband, a neckband): darker, with vertical ribs."""
    for yy in range(max(0, y0), min(ctx.h, y1)):
        for xx in range(ctx.w):
            scale_px(ctx, xx, yy, k * (0.93 if xx % 2 else 1.04))


def hem(ctx, yy, k=0.78, stitch_colour=None):
    """A turned hem along row yy (the garment's lowest row) with a line of stitching above it."""
    for xx in range(ctx.w):
        scale_px(ctx, xx, yy, k)
        scale_px(ctx, xx, yy - 1, 0.93)
    if stitch_colour and yy - 2 >= 0:
        stitch(ctx, stitch_colour, [(0, yy - 2), (ctx.w - 1, yy - 2)], alpha=0.45)


def seam_down(ctx, xx, k=0.8):
    for yy in range(ctx.h):
        scale_px(ctx, xx, yy, k)


def cut(ctx):
    clear(ctx, 0, 0, ctx.w, ctx.h)


def punch(ctx, xx, yy):
    """A see-through pixel (the garment opens there)."""
    if 0 <= xx < ctx.w and 0 <= yy < ctx.h:
        ctx.img.putpixel((ctx.x + xx, ctx.y + yy), (0, 0, 0, 0))


