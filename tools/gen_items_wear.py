def item_json(code, spec):
    slot = spec["slot"]
    t = TRANSFORMS[slot]
    attrs = {"clothescategory": slot, "wearableAttachment": True}
    attrs.update(spec["attrs"])
    if spec["warmth"]:
        attrs["warmth"] = spec["warmth"]
    # The body the clothes are drawn on in the inventory, the hand and the ground is the player's model with its own
    # texture key: as vanilla's clothes, that is made transparent, so only the garment shows
    textures = dict({"seraph": {"base": "game:block/transparent"}}, **spec["textures"])
    data = {"code": code, "storageFlags": 128, "behaviors": [{"name": "Wearable"}], "attributes": attrs,
            "shape": spec["shape"], "textures": textures, "creativeinventory": INV, "renderAlphaTest": 0.25}
    top = dict(spec["top"])
    ground = top.pop("ground", None)
    data.update(top)
    if slot == "foot":
        # As vanilla's shoes: set down in pairs on the floor
        data["behaviors"].append({"name": "GroundStorable", "properties": {"layout": "Quadrants",
                                  "collisionBox": {"x1": 0, "y1": 0, "z1": 0, "x2": 1, "y2": 0.25, "z2": 1}}})
        attrs["groundStorageTransform"] = {"translation": {"x": 0, "y": 0.011, "z": 0}}
    if slot == "head" and "hazmat" not in attrs:
        data["heldTpIdleAnimation"] = "holdunderarm"
    data["guiTransform"] = t["gui"]
    data["tpHandTransform"] = t["tp"]
    data["groundTransform"] = ground or t["ground"]
    return data


