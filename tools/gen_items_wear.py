def vanilla_root():
    for base in (os.environ.get("VINTAGE_STORY"), os.path.join(os.environ.get("APPDATA", ""), "Vintagestory")):
        if base and os.path.isdir(os.path.join(base, "assets", "survival")):
            return os.path.join(base, "assets", "survival")
    raise SystemExit("gen_items_wear: set VINTAGE_STORY to the game folder (vanilla's clothing shapes are read from it)")


def load_json5(path):
    import json5
    with open(path, encoding="utf-8-sig") as f:
        return json5.loads(f.read())


def write_json(path, data, comment):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    text = "// Generated by tools/gen_items_wear.py. " + comment + "\n" + json.dumps(data, indent="\t", ensure_ascii=False)
    with open(path, "w", encoding="utf-8", newline=NL) as f:
        f.write(text + "\n")


# ====================================================================================================================
# Painting: a face of a garment
# ====================================================================================================================
# Every face is painted through a context like rig.py's (ctx.img, ctx.x, ctx.y, ctx.w, ctx.h, ctx.face, ctx.rng) plus
# ctx.part (the body part it sits on: torso_u, torso_l, thigh_r, shin_l, uarm_r, farm_l, neck, hood, tail_f, inside,
# collar_w, waist_w, ...), ctx.side ("front", "back", "out", "in", "top", "bottom") and ctx.units (its size in shape
# units). Side faces run top to bottom; on a front face u runs from the wearer's right to their left.

FRONT_OF = {"west": "front", "east": "back", "up": "top", "down": "bottom"}


def side_of(part, face):
    if face in FRONT_OF:
        return FRONT_OF[face]
    # Right limbs sit at low z (north is their outside), left ones at high z
    if part.endswith("_r"):
        return "out" if face == "north" else "in"
    if part.endswith("_l"):
        return "out" if face == "south" else "in"
    return "side"


class Ctx:
    pass


def make_ctx(img, x, y, w, h, face, part, rng, units=(1, 1), name=""):
    ctx = Ctx()
    ctx.img, ctx.draw = img, ImageDraw.Draw(img)
    ctx.x, ctx.y, ctx.w, ctx.h = x, y, w, h
    ctx.face, ctx.part, ctx.rng, ctx.units, ctx.name = face, part, rng, units, name
    ctx.side = side_of(part, face)
    ctx.baked = False
    return ctx


def put(ctx, xx, yy, colour, alpha=1.0):
    """One pixel in face coordinates (clipped), mixed over what is there by alpha."""
    if not (0 <= xx < ctx.w and 0 <= yy < ctx.h):
        return
    px = ctx.img.load()
    old = px[ctx.x + xx, ctx.y + yy]
    if alpha >= 1 or old[3] == 0:
        px[ctx.x + xx, ctx.y + yy] = clamp(colour) + (255,)
    else:
        px[ctx.x + xx, ctx.y + yy] = mix(old[:3], colour, alpha) + (255,)


def scale_px(ctx, xx, yy, k):
    if not (0 <= xx < ctx.w and 0 <= yy < ctx.h):
        return
    px = ctx.img.load()
    c = px[ctx.x + xx, ctx.y + yy]
    if c[3]:
        px[ctx.x + xx, ctx.y + yy] = clamp((c[0] * k, c[1] * k, c[2] * k)) + (c[3],)


def clear(ctx, x0, y0, x1, y1):
    """Makes face pixels [x0, x1) x [y0, y1) transparent: the garment ends there."""
    px = ctx.img.load()
    for yy in range(max(0, y0), min(ctx.h, y1)):
        for xx in range(max(0, x0), min(ctx.w, x1)):
            px[ctx.x + xx, ctx.y + yy] = (0, 0, 0, 0)


def keep_top(ctx, rows):
    clear(ctx, 0, rows, ctx.w, ctx.h)


def hline(ctx, yy, colour, alpha=1.0, x0=0, x1=None):
    for xx in range(x0, ctx.w if x1 is None else x1):
        put(ctx, xx, yy, colour, alpha)


def vline(ctx, xx, colour, alpha=1.0, y0=0, y1=None):
    for yy in range(y0, ctx.h if y1 is None else y1):
        put(ctx, xx, yy, colour, alpha)


def box(ctx, x0, y0, x1, y1, colour, alpha=1.0):
    for yy in range(y0, y1):
        for xx in range(x0, x1):
            put(ctx, xx, yy, colour, alpha)


def stitch(ctx, colour, pts, alpha=0.8, every=2):
    """A dashed line of stitching through face points [(x, y), ...] (straight runs)."""
    n = 0
    for (x0, y0), (x1, y1) in zip(pts, pts[1:]):
        steps = max(abs(x1 - x0), abs(y1 - y0), 1)
        for i in range(steps + 1):
            if n % every == 0:
                put(ctx, round(x0 + (x1 - x0) * i / steps), round(y0 + (y1 - y0) * i / steps), colour, alpha)
            n += 1


def cloth(ctx, base, kind="plain", amount=4.0, mottle=0.07):
    """A cloth face: lit softly from above (rig.shade_fill, gentle at the edges so pieces of one garment meet without a
    rim), then its weave."""
    rig.shade_fill(ctx, base, var=0.03, light=0.06, dark=0.07, ao=0.08, ao_px=2, mottle=mottle, drift=0.12, cap=4, hue=0.02)
    if kind:
        rig.weave(ctx, amount=amount, kind=kind, slubs=0.03)


def grime(ctx, colour, rows_from_bottom, strength=0.35, chance=0.6):
    """Dirt worked into the bottom rows (a hem, a cuff, the seat of a sleeve), patchy."""
    for yy in range(ctx.h - rows_from_bottom, ctx.h):
        t = (yy - (ctx.h - rows_from_bottom) + 1) / rows_from_bottom
        for xx in range(ctx.w):
            if ctx.rng.random() < chance:
                put(ctx, xx, yy, colour, strength * t * (0.5 + 0.5 * ctx.rng.random()))


def stain(ctx, cx, cy, r, colour, strength=0.3):
    """A soft blotch with a darker tide line."""
    for yy in range(int(cy - r - 1), int(cy + r + 2)):
        for xx in range(int(cx - r - 1), int(cx + r + 2)):
            d = math.hypot(xx - cx, (yy - cy) * 1.2) / max(0.5, r)
            if d <= 1.0:
                a = strength * (0.55 + 0.45 * d) * (0.8 + 0.4 * ctx.rng.random())
                put(ctx, xx, yy, colour, min(1.0, a))


def wear_spots(ctx, colour, chance=0.04, strength=0.35):
    """Pale rubbed spots (pilling, fading) over a face."""
    for yy in range(ctx.h):
        for xx in range(ctx.w):
            if ctx.rng.random() < chance:
                put(ctx, xx, yy, colour, strength * (0.5 + ctx.rng.random() * 0.5))


def rows(ctx, units):
    """Face pixels for a length in shape units."""
    return int(round(units * TEXEL))


