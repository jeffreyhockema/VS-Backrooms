def tr(x=0.0, y=0.0, z=0.0, rx=0, ry=0, rz=0, ox=None, oy=None, oz=None, scale=1.0, rotate=None):
    t = {"translation": {"x": x, "y": y, "z": z}, "rotation": {"x": rx, "y": ry, "z": rz}}
    if ox is not None:
        t["origin"] = {"x": ox, "y": oy, "z": oz}
    t["scale"] = scale
    if rotate is not None:
        t["rotate"] = rotate
    return t


