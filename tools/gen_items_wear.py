class Wear:
    """A clothing shape of our own (its texture key must be its own: worn together, two items that share a key draw
    with one texture, so the hood would wear the suit's): elements on the seraph's body parts (stepParentName), each face given a texture
    rectangle by a shelf packer and painted by `paint(ctx)` with ctx.part = the element's `part` tag."""

    def __init__(self, key, paint, atlas_w=32, seed=1):
        self.key, self.paint, self.atlas_w, self.seed = key, paint, atlas_w, seed
        self.roots, self.all = [], []

    def el(self, name, frm, to, part, parent=None, step=None, faces=rig.FACES, rot=None, origin=None):
        e = {"name": name, "from": list(frm), "to": list(to), "part": part, "faces": tuple(faces), "children": [],
             "rot": rot or (0, 0, 0), "origin": origin, "step": step}
        (parent["children"] if parent else self.roots).append(e)
        self.all.append(e)
        return e

    @staticmethod
    def face_units(e, face):
        sx, sy, sz = (abs(e["to"][i] - e["from"][i]) for i in range(3))
        return {"north": (sx, sy), "south": (sx, sy), "east": (sz, sy), "west": (sz, sy), "up": (sx, sz), "down": (sx, sz)}[face]

    def build(self, texture_path):
        rects = []
        for e in self.all:
            for f in e["faces"]:
                w, h = self.face_units(e, f)
                rects.append((max(1, math.ceil(h * TEXEL - 1e-6)), max(1, math.ceil(w * TEXEL - 1e-6)), e, f))
        rects.sort(key=lambda r: (-r[0], -r[1], r[2]["name"], r[3]))
        width = self.atlas_w * TEXEL
        x = y = shelf = 0
        uv = {}
        for ph, pw, e, f in rects:
            if x + pw > width:
                x, y, shelf = 0, y + shelf + 1, 0
            uv[(e["name"], f)] = (x, y, pw, ph)
            x += pw + 1
            shelf = max(shelf, ph)
        height = 8
        while height < y + shelf + 1:
            height *= 2
        img = Image.new("RGBA", (width, height), (0, 0, 0, 0))
        for i, e in enumerate(self.all):
            for f in e["faces"]:
                x0, y0, pw, ph = uv[(e["name"], f)]
                ctx = make_ctx(img, x0, y0, pw, ph, f, e["part"], random.Random(self.seed * 7919 + i * 13 + rig.FACES.index(f)),
                               self.face_units(e, f), e["name"])
                self.paint(ctx)

        def element(e):
            out = {"name": e["name"], "from": [round(v, 4) for v in e["from"]], "to": [round(v, 4) for v in e["to"]]}
            if e["step"]:
                out["stepParentName"] = e["step"]
            if any(e["rot"]) or e["origin"]:
                out["rotationOrigin"] = [round(v, 4) for v in (e["origin"] or e["from"])]
            for axis, v in zip("XYZ", e["rot"]):
                if v:
                    out["rotation" + axis] = v
            out["faces"] = {}
            for f in rig.FACES:
                if f not in e["faces"]:
                    continue
                x0, y0, pw, ph = uv[(e["name"], f)]
                out["faces"][f] = {"texture": "#" + self.key, "uv": [x0 / TEXEL, y0 / TEXEL, (x0 + pw) / TEXEL, (y0 + ph) / TEXEL]}
            if e["children"]:
                out["children"] = [element(c) for c in e["children"]]
            return out

        shape = {
            "editor": {"backDropShape": "entity/humanoid/seraph", "allAngles": True, "entityTextureMode": True},
            "textureWidth": self.atlas_w, "textureHeight": height // TEXEL,
            "textureSizes": {self.key: [self.atlas_w, height // TEXEL]},
            "textures": {self.key: texture_path},
            "elements": [element(e) for e in self.roots],
        }
        return shape, img


